        "par la nature du modèle actif : SHAP dispose, pour les modèles à base d'arbres tels que "
        "CatBoost, d'un explicateur exact et rapide (TreeExplainer), calculant les contributions "
        "réelles du modèle plutôt qu'une approximation locale par un modèle de substitution linéaire, "
        "comme le fait LIME. LIME reste pertinent pour des modèles boîte noire dépourvus d'un tel "
