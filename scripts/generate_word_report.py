def add_body_paragraph(doc: Document, text: str, *, italic=False, bold=False) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.italic = italic
    run.bold = bold


def add_figure(doc: Document, image_path: Path, caption: str, width_in: float = 5.7) -> None:
    _counters["figure"] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(image_path), width=Inches(width_in))
    cap = doc.add_paragraph(style="Caption" if "Caption" in [s.name for s in doc.styles] else None)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = cap.add_run(f"Figure {_counters['figure']}. {caption}")
    run.italic = True
    run.font.size = Pt(10.5)


def add_table(doc: Document, headers: list[str], rows: list[list[str]], caption: str) -> None:
    _counters["table"] += 1
    cap = doc.add_paragraph(style="Caption" if "Caption" in [s.name for s in doc.styles] else None)
    run = cap.add_run(f"Tableau {_counters['table']}. {caption}")
    run.italic = True
    run.font.size = Pt(10.5)

    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = ""
        run = hdr_cells[i].paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(10.5)
    for row_data in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row_data):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(val))
            run.font.size = Pt(10.5)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)


def add_placeholder_frame(doc: Document, title: str, explanation: list[str], height_in: float = 4.3) -> None:
    """A titled explanation followed by a large empty bordered frame,
    deliberately left blank for the reader to paste the corresponding
    UML diagram image (see docs/diagrams/) by hand."""

    h = doc.add_heading(title, level=3)
    h.paragraph_format.page_break_before = False
    for para in explanation:
        add_body_paragraph(doc, para)

    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.rows[0].cells[0]
    cell.width = Inches(6.3)
    tr = table.rows[0]._tr
    trPr = tr.get_or_add_trPr()
    trHeight = OxmlElement("w:trHeight")
    trHeight.set(qn("w:val"), str(int(height_in * 1440)))
    trHeight.set(qn("w:hRule"), "atLeast")
    trPr.append(trHeight)

    tcPr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "dashed")
        el.set(qn("w:sz"), "12")
        el.set(qn("w:color"), "64748B")
        borders.append(el)
    tcPr.append(borders)

    cell.vertical_alignment = 1  # center
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("[ Espace réservé — coller ici l'image du diagramme correspondant ]")
    run.italic = True
    run.font.size = Pt(11)
    run.font.color.rgb = RGBColor(0x94, 0xA3, 0xB8)

    doc.add_paragraph()


