def _add_field(paragraph, field_code: str, placeholder_text: str = "") -> None:
    """Inserts a Word field (e.g. PAGE, TOC) into a paragraph."""

    run = paragraph.add_run()

    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")

    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = field_code

    fld_separate = OxmlElement("w:fldChar")
    fld_separate.set(qn("w:fldCharType"), "separate")

    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")

    r = run._r
    r.append(fld_begin)
    r.append(instr)
    r.append(fld_separate)
    if placeholder_text:
        t = OxmlElement("w:t")
        t.text = placeholder_text
        r.append(t)
    r.append(fld_end)


def add_table_of_contents(doc: Document) -> None:
    heading = doc.add_paragraph("Table des matières", style="TOC Heading")
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = doc.add_paragraph()
    _add_field(p, 'TOC \\o "1-3" \\h \\z \\u',
               "Sommaire généré automatiquement — clic droit puis « Mettre à jour les champs » "
               "dans Word pour l'afficher (ou F9).")
    doc.add_page_break()


def add_page_number_field(paragraph) -> None:
    _add_field(paragraph, "PAGE")


def set_page_margins(section, top=2.5, bottom=2.5, left=3.0, right=2.5) -> None:
    section.top_margin = Cm(top)
    section.bottom_margin = Cm(bottom)
    section.left_margin = Cm(left)
    section.right_margin = Cm(right)


